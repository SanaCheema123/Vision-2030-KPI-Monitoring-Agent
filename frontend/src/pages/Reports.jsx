import { Download, FileText, Printer } from "lucide-react";
import { kpis } from "../data/demoData";

export default function Reports() {
  const generateReport = () => {
    const text = `
VISION 2030 KPI EXECUTIVE REPORT
================================

Total KPIs: ${kpis.length}

${kpis
  .map(
    (k) =>
      `${k.name}
Target: ${k.target}${k.unit}
Actual: ${k.actual}${k.unit}
Status: ${k.status}
`
  )
  .join("\n")}

Generated by Vision 2030 KPI Agent.
`;

    const blob = new Blob([text], { type: "text/plain" });
    const url = URL.createObjectURL(blob);

    const link = document.createElement("a");
    link.href = url;
    link.download = "vision2030-executive-report.txt";
    link.click();

    URL.revokeObjectURL(url);
  };

  return (
    <div className="page">
      <div className="page-intro">
        <div>
          <h2>Executive Reports</h2>
          <p>Generate a concise performance report for decision makers.</p>
        </div>

        <button className="primary-button" onClick={generateReport}>
          <Download size={18} />
          Generate Report
        </button>
      </div>

      <div className="report-preview">
        <div className="report-header">
          <div className="report-logo">
            <FileText size={24} />
          </div>

          <div>
            <h2>Vision 2030 Performance Report</h2>
            <span>Executive Summary · 2027</span>
          </div>

          <button className="icon-button" onClick={() => window.print()}>
            <Printer size={19} />
          </button>
        </div>

        <div className="report-line" />

        <h3>KPI Summary</h3>

        <div className="report-table">
          <div className="report-table-head">
            <span>KPI</span>
            <span>Target</span>
            <span>Actual</span>
            <span>Status</span>
          </div>

          {kpis.map((kpi) => (
            <div className="report-table-row" key={kpi.id}>
              <span>{kpi.name}</span>
              <span>
                {kpi.target}
                {kpi.unit}
              </span>
              <span>
                {kpi.actual}
                {kpi.unit}
              </span>
              <span>{kpi.status}</span>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}